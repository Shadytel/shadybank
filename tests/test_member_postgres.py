"""Optional real PostgreSQL ledger test, using a dedicated disposable test schema."""

import asyncio
import json
import os
import unittest
from decimal import Decimal
from pathlib import Path
from types import SimpleNamespace
from unittest.mock import patch
from uuid import uuid4

from aiohttp import web
from passlib.hash import argon2
from test_member_api import CARD, RECIPIENT, PIN, KEY, Redis, request
from member_api import MemberAPI


@unittest.skipUnless(os.getenv('SHADYBANK_TEST_DSN'),'Set a dedicated test database DSN')
class PostgresMemberTests(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self):
        import asyncpg
        self.schema='member_test_'+uuid4().hex
        self.control=await asyncpg.connect(os.environ['SHADYBANK_TEST_DSN'])
        await self.control.execute('CREATE SCHEMA '+self.schema)
        self.pool=await asyncpg.create_pool(os.environ['SHADYBANK_TEST_DSN'],
                                           server_settings={'search_path':self.schema})
        self.addAsyncCleanup(self.cleanup_database)
        await self.pool.execute((Path(__file__).resolve().parents[1]/'srv/data/postgres.sql').read_text())
        for name,value,pan in (('Fixture source',Decimal('100.00'),CARD),('Fixture target',Decimal('5.00'),RECIPIENT)):
            account=await self.pool.fetchval('INSERT INTO accounts(name,balance,available) VALUES($1,$2,$2) RETURNING id',name,value)
            await self.pool.execute("INSERT INTO cards(pan,account_id,expires,status) VALUES($1,$2,'3801','activated')",pan,account)
            await self.pool.execute("INSERT INTO secrets(account_id,type,secret) VALUES($1,'pin',$2)",account,argon2.hash(PIN))
        daemon=SimpleNamespace(_app=web.Application(),_psql_pool=self.pool,_redis_pool=Redis())
        with patch.dict(os.environ,{'SHADYBANK_MEMBER_SERVICE_KEY':KEY}):
            self.api=MemberAPI(daemon)
        self.token=json.loads((await self.api.login(request({'pan':CARD,'pin':PIN}))).text)['token']

    async def cleanup_database(self):
        await self.pool.close()
        # This identifier is generated by this test, not derived from an environment variable.
        await self.control.execute('DROP SCHEMA '+self.schema+' CASCADE')
        await self.control.close()

    async def test_concurrent_identical_request_posts_once(self):
        form={'recipient_pan':RECIPIENT,'amount':'12.50','request_id':str(uuid4())}
        results=await asyncio.gather(*(self.api.transfer(request(form,self.token)) for _ in range(2)))
        self.assertEqual(json.loads(results[0].text),json.loads(results[1].text))
        values=await self.pool.fetch('SELECT balance,available FROM accounts ORDER BY id')
        self.assertEqual([r['balance'] for r in values],[Decimal('87.50'),Decimal('17.50')])
        self.assertEqual(await self.pool.fetchval('SELECT COUNT(*) FROM transactions'),1)

    async def test_concurrent_distinct_transfers_do_not_overspend(self):
        results=await asyncio.gather(*(self.api.transfer(request({'recipient_pan':RECIPIENT,'amount':'80.00',
            'request_id':str(uuid4())},self.token)) for _ in range(2)),return_exceptions=True)
        self.assertEqual(sum(isinstance(r,web.Response) and r.status==201 for r in results),1)
        self.assertEqual(sum(isinstance(r,web.HTTPConflict) for r in results),1)
        values=await self.pool.fetch('SELECT balance,available FROM accounts ORDER BY id')
        self.assertEqual([r['balance'] for r in values],[Decimal('20.00'),Decimal('85.00')])
        self.assertEqual(await self.pool.fetchval('SELECT COUNT(*) FROM transactions'),1)
